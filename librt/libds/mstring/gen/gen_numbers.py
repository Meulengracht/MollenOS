#!/bin/python3
# We download the following files:
# - https://unicode.org/Public/UNIDATA/extracted/DerivedNumericType.txt
# - https://unicode.org/Public/UNIDATA/extracted/DerivedNumericValues.txt
# and then use those to generate a way of checking number information

from urllib.request import urlopen
import argparse


def get_data(url):
    """
    Download the data from the given url.
    """
    return urlopen(url).read().decode("utf-8")


def download_number_tables():
    """
    Download the number tables data from the unicode.org website.
    """
    types = get_data("https://unicode.org/Public/UNIDATA/extracted/DerivedNumericType.txt")
    values = get_data("https://unicode.org/Public/UNIDATA/extracted/DerivedNumericValues.txt")
    return types, values


def parse_value_selector(s):
    if ".." in s:
        parts = s.split("..")
        start = int(parts[0], 16)
        end = int(parts[1], 16)
        return start, end
    else:
        v = int(s, 16)
        return v, v


def remove_hashtag_part(s):
    if "#" in s:
        parts = s.split("#")
        return parts[0].strip()
    return s.strip()


def parse_maybe_frac(s):
    if "/" in s:
        parts = s.split("/")
        num = int(parts[0].strip())
        denom = int(remove_hashtag_part(parts[1]))
        return num, denom
    else:
        num = int(remove_hashtag_part(s))
        return num, num


def parse_number_tables(types, values):
    """
    Parse the number types and values.

    The values are based on fields 6-8 of UnicodeData.txt, plus the fields
    kAccountingNumeric, kOtherNumeric, kPrimaryNumeric in the Unicode Han Database (Unihan).
    The derivations for these values are as follows.
     Numeric_Type=Decimal: When there is a value in field 6.
     Numeric_Type=Digit:   When there is a value in field 7, but not in field 6.
     Numeric_Type=Numeric: When there are values for kAccountingNumeric, kOtherNumeric, kPrimaryNumeric,
                           or there is a value in field 8, but not in field 7.
     Numeric_Type=None:    Otherwise

    All code points not explicitly listed for Numeric_Type
    have the value None.
    """
    type_map = {}

    # parse the types first
    # 00BC..00BE    ; Numeric # No   [3] VULGAR FRACTION ONE QUARTER..VULGAR FRACTION THREE QUARTERS
    # 2189          ; Numeric # No       VULGAR FRACTION ZERO THIRDS
    for line in types.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue

        parts = list(filter(None, line.split(" ")))
        if len(parts) < 3:
            continue

        vs, ve = parse_value_selector(parts[0].strip())
        t = parts[2].strip()

        for i in range(vs, ve + 1):
            type_map[i] = t

    descs = {}
    # parse the values (No = Number, other. Nd = Number, digit.)
    # 0D5A          ; 0.0375 ; ; 3/80 # No       MALAYALAM FRACTION THREE EIGHTIETHS
    # 1B53          ; 3.0 ; ; 3 # Nd       BALINESE DIGIT THREE
    for line in values.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue

        parts = list(filter(None, line.split(";")))
        if len(parts) < 3:
            continue

        try:
            vs, ve = parse_value_selector(parts[0].strip())
            dec = float(parts[1].strip())
            num, denom = parse_maybe_frac(parts[3].strip())
        except:
            print(f"failed to parse: {line} / {parts}")
            raise

        for i in range(vs, ve + 1):
            descs[i] = {
                "format": type_map[i],
                "value": dec,
                "numerator": num,
                "denominator": denom,
            }

    # sort mappings by key
    descs = sorted(descs.items(), key=lambda x: x[0])
    return descs


def write_header(out_path):
    """
    Write the header file to a file.
    """
    with open(out_path.replace(".c", ".h"), "w") as f:
        f.write("""\
/*
 * This file is generated by gen_numbers.py.
 * Do not edit this file directly.
 */
""")
        f.write("""\

#ifndef __UNICODE_DIGIT_H__
#define __UNICODE_DIGIT_H__
""")
        f.write("""\

#include <stddef.h>
#include <stdint.h>
""")
        f.write("""\

typedef enum {
    __DIGIT_TYPE_NONE,
    __DIGIT_TYPE_DECIMAL,
    __DIGIT_TYPE_DIGIT,
    __DIGIT_TYPE_NUMERIC
} __digit_type_t;

typedef struct {
    uint32_t       code;
    __digit_type_t type;
    int            numerator;
    int            denominator;
} __unicode_digit_t;

""")

        f.write("""\
extern const size_t g_unicodeDigitCount;
""")
        f.write("""\
extern const __unicode_digit_t g_unicodeDigitTable[];

""")
        f.write("""\
#endif //!__UNICODE_DIGIT_H__
""")


def type_to_enum(s):
    if s == "Decimal":
        return "__DIGIT_TYPE_DECIMAL"
    elif s == "Digit":
        return "__DIGIT_TYPE_DIGIT"
    elif s == "Numeric":
        return "__DIGIT_TYPE_NUMERIC"
    return "__DIGIT_TYPE_NONE"


def write_table(descs, out_path):
    """
    Write the table of case folding mappings to a file.
    """

    with open(out_path, "w") as f:
        f.write("""\
/*
 * This file is generated by gen_numbers.py.
 * Do not edit this file directly.
 */

""")
        headerName = out_path.replace(".c", ".h")
        f.write(f"#include <{headerName}>\n\n")

        f.write(f"const size_t         g_unicodeDigitCount = {len(descs)};\n", )
        f.write("const __unicode_digit_t g_unicodeDigitTable[] = {\n")
        f.write("    // uppercase, lowercase\n")
        for code, vals in descs:
            f.write("    { ")
            f.write("{0}, {1}, {2}, {3}".format(
                code,
                type_to_enum(vals["format"]),
                vals["numerator"],
                vals["denominator"]))
            f.write(" },\n")
        f.write("};\n\n")


def main(args):
    """
    Generate the table of number mappings.
    """
    types, values = download_number_tables()
    descs = parse_number_tables(types, values)

    # Write the table to a file.
    write_header(args.out)
    write_table(descs, args.out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description='Unicode helper script to generate properties.')
    parser.add_argument('--out', default="mstr_digits.c", help='Where to write the output file.')
    args = parser.parse_args()
    main(args)
