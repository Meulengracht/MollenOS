// AAPCS64 arguments arrive in x0..x5. The kernel ABI uses x8 for the
// service number, x0..x4 for arguments, and x0 for the result.
.text
.p2align 2
.globl _syscall
_syscall:
    mov x8, x0
    mov x0, x1
    mov x1, x2
    mov x2, x3
    mov x3, x4
    mov x4, x5
    svc #0
    ret
